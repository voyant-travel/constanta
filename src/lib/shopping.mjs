function record(value) {
  return value !== null && typeof value === "object" && !Array.isArray(value)
    ? value
    : undefined
}

function language(locale) {
  return typeof locale === "string" ? locale.split("-")[0].toLowerCase() : "en"
}

export function messagesFor(locale) {
  return DICTIONARIES[language(locale)] ?? DICTIONARIES.en
}

export function capabilityEndpoint(live, id, method) {
  const capabilities = record(live)?.capabilities
  if (!Array.isArray(capabilities)) return undefined
  const capability = capabilities.find((candidate) => {
    const value = record(candidate)
    return value?.id === id && value.available === true
  })
  const value = record(capability)
  if (typeof value?.endpoint !== "string" || !value.endpoint.startsWith("/")) return undefined
  if (method && Array.isArray(value.methods) && !value.methods.includes(method)) return undefined
  return value.endpoint
}

function safeEndpoint(endpoint, origin) {
  if (typeof endpoint !== "string" || !endpoint) throw new Error("Managed shopping is unavailable")
  const base = new URL(origin)
  const resolved = new URL(endpoint, base)
  if (resolved.origin !== base.origin) throw new Error("Capability endpoint must use the storefront origin")
  return resolved.href
}

function parsedScope(value) {
  const scope = record(value)
  const available = record(scope?.available)
  if (
    typeof scope?.marketId !== "string" ||
    typeof scope.locale !== "string" ||
    typeof scope.currency !== "string" ||
    !Array.isArray(available?.marketIds) ||
    !Array.isArray(available.locales) ||
    !Array.isArray(available.currencies)
  ) throw new Error("Managed shopping returned an invalid scope")
  return scope
}

function envelopeData(payload) {
  const data = record(record(payload)?.data)
  if (!data) throw new Error("Managed shopping returned an invalid response")
  return data
}

function presentedMoney(value, expectedCurrency) {
  const money = record(value)
  const presentation = record(money?.presentation)
  if (
    typeof presentation?.amount !== "string" ||
    typeof presentation.currency !== "string" ||
    presentation.currency !== expectedCurrency
  ) throw new Error("Managed shopping returned money outside the resolved currency")
}

function validateSearchResult(data) {
  if (!["indexed-inspiration", "flight", "stay", "package", "cruise"].includes(data.kind)) {
    throw new Error("Managed shopping returned an unknown result kind")
  }
  const scope = parsedScope(data.scope)
  const rows = data.kind === "indexed-inspiration"
    ? (Array.isArray(data.groups) ? data.groups.flatMap((group) => Array.isArray(record(group)?.items) ? record(group).items : []) : [])
    : (Array.isArray(data.offers) ? data.offers : [])
  for (const candidate of rows) {
    const row = record(candidate)
    const money = row?.price ?? row?.priceFrom
    if (money !== undefined) presentedMoney(money, scope.currency)
  }
  return data
}

function validateTrip(data) {
  if (
    typeof data.selectionRef !== "string" ||
    !Number.isInteger(data.revision) ||
    !Array.isArray(data.items)
  ) throw new Error("Managed Trips returned an invalid response")
  parsedScope(data.scope)
  return data
}

function validateTripBooking(data) {
  const outcome = record(data.outcome)
  const session = record(outcome?.session)
  const target = record(session?.target)
  if (
    outcome?.kind !== "session_created" ||
    typeof session?.id !== "string" ||
    !Number.isInteger(session.revision) ||
    target?.kind !== "managed_itinerary" ||
    (data.bookingSessionCapability !== undefined &&
      (typeof data.bookingSessionCapability !== "string" ||
        !/^bcap_[A-Za-z0-9_-]{43,}$/.test(data.bookingSessionCapability)))
  ) throw new Error("Managed Trips returned an invalid booking session")
  return data
}

function requestedScope(scope) {
  return {
    ...(typeof scope.marketId === "string" ? { marketId: scope.marketId } : {}),
    ...(typeof scope.locale === "string" ? { locale: scope.locale } : {}),
    ...(typeof scope.currency === "string" ? { currency: scope.currency } : {}),
  }
}

export class ShoppingHttpError extends Error {
  constructor(message, status, code) {
    super(message)
    this.name = "ShoppingHttpError"
    this.status = status
    this.code = code
  }
}

async function responseBody(response) {
  const payload = await response.json().catch(() => undefined)
  if (!response.ok) {
    const body = record(payload)
    const code = typeof body?.error === "string" ? body.error : "shopping_request_failed"
    throw new ShoppingHttpError(code.replaceAll("_", " "), response.status, code)
  }
  return payload
}

/**
 * Browser adapter for the managed Storefront boundary. It only submits public
 * scope preferences and opaque references. Provider, customer, booking,
 * payment, and FX authority have no representation in this client.
 */
export function createShoppingClient(options) {
  const fetchImpl = options.fetchImpl ?? globalThis.fetch
  const origin = options.origin ?? globalThis.location?.origin
  if (!origin) throw new Error("A storefront origin is required")
  let scope = { locale: options.locale }
  let trip
  let booking
  let pendingBook
  let tripMutationQueue = Promise.resolve()
  let scopeVersion = 0

  async function request(endpoint, method, body) {
    const response = await fetchImpl(safeEndpoint(endpoint, origin), {
      method,
      headers: { Accept: "application/json", "Content-Type": "application/json" },
      body: JSON.stringify(body),
    })
    return responseBody(response)
  }

  return {
    scope: () => ({ ...scope }),
    trip: () => trip,
    booking: () => booking,
    chooseScope(next) {
      scopeVersion += 1
      // A market is a server-resolved scope identity, not a browser
      // preference. Retaining it while locale or currency changes creates an
      // impossible mixed scope. Only send a market when an explicit market
      // picker supplies one in this transition.
      scope = requestedScope(next)
    },
    async search(intent) {
      const requestedVersion = scopeVersion
      const data = validateSearchResult(
        envelopeData(await request(options.searchEndpoint, "POST", {
          scope: requestedScope(scope),
          intent,
        })),
      )
      // A response for an older preference must not undo a newer locale or
      // currency choice. The UI schedules a follow-up search for that choice.
      if (scopeVersion === requestedVersion) scope = data.scope
      return data
    },
    add(kind, offerRef) {
      const mutate = async () => {
        if (booking) throw new Error("This Trip has already been booked")
        try {
          if (!trip) {
            trip = validateTrip(envelopeData(await request(options.tripsEndpoint, "POST", {
              scope: requestedScope(scope),
              offers: [{ kind, offerRef }],
            })))
          } else {
            trip = validateTrip(envelopeData(await request(options.tripsEndpoint, "PATCH", {
              selectionRef: trip.selectionRef,
              expectedRevision: trip.revision,
              mutation: { kind: "add", offer: { kind, offerRef } },
            })))
          }
          scope = trip.scope
          return trip
        } catch (error) {
          if (error instanceof ShoppingHttpError && error.status === 409) trip = undefined
          throw error
        }
      }
      const result = tripMutationQueue.then(mutate, mutate)
      tripMutationQueue = result.then(() => undefined, () => undefined)
      return result
    },
    async remove(itemRef) {
      return this.mutate({ kind: "remove", itemRef })
    },
    async reorder(itemRefs) {
      return this.mutate({ kind: "reorder", itemRefs })
    },
    mutate(mutation) {
      const mutate = async () => {
        if (booking) throw new Error("This Trip has already been booked")
        if (!trip) throw new Error("Start a Trip before updating it")
        try {
          trip = validateTrip(envelopeData(await request(options.tripsEndpoint, "PATCH", {
            selectionRef: trip.selectionRef,
            expectedRevision: trip.revision,
            mutation,
          })))
          scope = trip.scope
          return trip
        } catch (error) {
          // A 409 proves this browser's revision is stale. The public contract
          // deliberately exposes no read-by-reference endpoint, so replaying is
          // unsafe. Clear the stale capability and require fresh search refs.
          if (error instanceof ShoppingHttpError && error.status === 409) trip = undefined
          throw error
        }
      }
      const result = tripMutationQueue.then(mutate, mutate)
      tripMutationQueue = result.then(() => undefined, () => undefined)
      return result
    },
    async book() {
      if (!trip) throw new Error("Start a Trip before booking it")
      const requestFingerprint = `${trip.selectionRef}:${trip.revision}`
      if (!pendingBook || pendingBook.fingerprint !== requestFingerprint) {
        const randomUUID = options.randomUUID ?? (() => globalThis.crypto.randomUUID())
        pendingBook = {
          fingerprint: requestFingerprint,
          key: `theme-book-itinerary-${randomUUID()}`.slice(0, 128),
        }
      }
      try {
        booking = validateTripBooking(envelopeData(await request(options.bookEndpoint, "POST", {
          selectionRef: trip.selectionRef,
          expectedRevision: trip.revision,
          idempotencyKey: pendingBook.key,
        })))
        pendingBook = undefined
        return booking
      } catch (error) {
        if (
          error instanceof ShoppingHttpError &&
          (error.status === 403 || error.status === 409)
        ) {
          trip = undefined
          pendingBook = undefined
        }
        throw error
      }
    },
    bookRetryKey: () => pendingBook?.key,
  }
}

export function formatPresentationMoney(value, locale) {
  const presentation = record(record(value)?.presentation)
  if (typeof presentation?.amount !== "string" || typeof presentation.currency !== "string") return undefined
  const amount = Number(presentation.amount)
  if (!Number.isFinite(amount)) return undefined
  try {
    return new Intl.NumberFormat(locale, {
      style: "currency",
      currency: presentation.currency,
      currencyDisplay: "narrowSymbol",
    }).format(amount)
  } catch {
    return `${presentation.amount} ${presentation.currency}`
  }
}

function text(form, name) {
  return String(new FormData(form).get(name) ?? "").trim()
}

function integer(form, name, fallback = 1) {
  const value = Number.parseInt(text(form, name), 10)
  return Number.isInteger(value) ? value : fallback
}

export function intentFromForm(form) {
  const kind = text(form, "kind")
  if (kind === "indexed-inspiration") {
    const query = text(form, "query")
    const destination = text(form, "inspirationDestination")
    const fromDate = text(form, "fromDate")
    const toDate = text(form, "toDate")
    return {
      kind,
      groups: ["tours", "excursions", "experiences", "activities"].map((group) => ({
        group,
        ...(query ? { query } : {}),
        ...(destination ? { destination: { query: destination } } : {}),
        ...(fromDate ? { fromDate } : {}),
        ...(toDate ? { toDate } : {}),
        pagination: { limit: 12 },
      })),
    }
  }
  if (kind === "flight") {
    return {
      kind,
      slices: [{
        origin: text(form, "flightOrigin").toUpperCase(),
        destination: text(form, "flightDestination").toUpperCase(),
        departureDate: text(form, "departureDate"),
      }],
      travelers: { adults: integer(form, "flightAdults") },
      cabin: text(form, "cabin"),
      ...(new FormData(form).get("directOnly") === "on" ? { directOnly: true } : {}),
      pagination: { limit: 20 },
    }
  }
  if (kind === "stay") {
    return {
      kind,
      // The managed Connect stay gateway accepts canonical destination fields;
      // the visible destination control is a city picker/text entry.
      destination: { city: text(form, "stayDestination") },
      checkIn: text(form, "checkIn"),
      checkOut: text(form, "checkOut"),
      rooms: [{ adults: integer(form, "stayAdults") }],
      pagination: { limit: 20 },
    }
  }
  if (kind === "cruise") {
    const query = text(form, "cruiseQuery")
    const departureDateFrom = text(form, "cruiseFrom")
    const departureDateTo = text(form, "cruiseTo")
    const cruiseType = text(form, "cruiseType")
    const children = integer(form, "cruiseChildren", 0)
    return {
      kind,
      ...(query ? { query } : {}),
      ...(departureDateFrom ? { departureDateFrom } : {}),
      ...(departureDateTo ? { departureDateTo } : {}),
      travelers: {
        adults: integer(form, "cruiseAdults", 2),
        ...(children > 0 ? { children } : {}),
      },
      ...(cruiseType ? { cruiseTypes: [cruiseType] } : {}),
      limit: 20,
    }
  }
  return {
    kind: "package",
    origin: text(form, "packageOrigin").toUpperCase(),
    // Connect's dynamic-package provider requires an explicit city/country
    // destination so it can be re-resolved deterministically for quote and
    // booking.
    destination: { city: text(form, "packageDestination") },
    departureDateFrom: text(form, "packageFrom"),
    departureDateTo: text(form, "packageTo"),
    nights: { min: integer(form, "nightsMin", 3), max: integer(form, "nightsMax", 7) },
    travelers: { adults: integer(form, "packageAdults") },
    pagination: { limit: 20 },
  }
}
